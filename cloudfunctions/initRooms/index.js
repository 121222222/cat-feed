exports.main = async (event, context) => {
  const { action, building } = event;
  
  try {
    // 清空现有数据（可选）
    if (action === 'clear') {
      // 分批删除
      let deleted = 0;
      while (true) {
        const res = await db.collection('valid_rooms').limit(100).get();
        if (res.data.length === 0) break;
        
        for (const item of res.data) {
          await db.collection('valid_rooms').doc(item._id).remove();
          deleted++;
        }
      }
      return { success: true, message: `已清空 ${deleted} 条记录` };
    }
    
    // 初始化指定楼栋或全部楼栋
    const buildings = building ? [building] : Object.keys(buildingRooms);
    let totalAdded = 0;
    const results = [];
    
    for (const bld of buildings) {
      const ranges = buildingRooms[bld];
      if (!ranges) {
        results.push({ building: bld, error: '未找到该楼栋配置' });
        continue;
      }
      
      let addedCount = 0;
      
      for (const range of ranges) {
        const roomNumbers = parseRange(range);
        
        for (const roomNumber of roomNumbers) {
          // 检查是否已存在
          const existing = await db.collection('valid_rooms').where({
            building: bld,
            roomNumber: roomNumber
          }).get();
          
          if (existing.data.length === 0) {
            // 添加新记录
            await db.collection('valid_rooms').add({
              data: {
                building: bld,
                roomNumber: roomNumber,
                status: 'active',
                createTime: db.serverDate()
              }
            });
            addedCount++;
          }
        }
      }
      
      totalAdded += addedCount;
      results.push({ building: bld, added: addedCount });
    }
    
    return { 
      success: true, 
      totalAdded,
      results,
      message: `成功添加 ${totalAdded} 个房间号`
    };
  } catch (err) {
    console.error('初始化房间号失败:', err);
    return { success: false, error: err.message };
  }
};
